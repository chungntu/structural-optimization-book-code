def draw_dim_h(ax, x1, x2, y, label, offset=-1.5):
    yo = y + offset
    ax.plot([x1, x1], [y - 0.1, yo - 0.1], 'k--', linewidth=0.6)
    ax.plot([x2, x2], [y - 0.1, yo - 0.1], 'k--', linewidth=0.6)
    ax.annotate('', xy=(x1, yo), xytext=(x2, yo),
                arrowprops=dict(arrowstyle='<->', color='black', lw=1.2))
    ax.text((x1+x2)/2, yo - 0.3, label, fontsize=9, ha='center', va='top',
            fontweight='bold')

def draw_dim_v(ax, x, y1, y2, label, offset=1.5):
    xo = x + offset
    ax.plot([x + 0.1, xo + 0.1], [y1, y1], 'k--', linewidth=0.6)
    ax.plot([x + 0.1, xo + 0.1], [y2, y2], 'k--', linewidth=0.6)
    ax.annotate('', xy=(xo, y1), xytext=(xo, y2),
                arrowprops=dict(arrowstyle='<->', color='black', lw=1.2))
    ax.text(xo + 0.3, (y1+y2)/2, label, fontsize=9, ha='left', va='center',
            fontweight='bold', rotation=90)

